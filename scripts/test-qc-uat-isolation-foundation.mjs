import {assertDemoEnvironment,candidateRules,demoProject,probePath,selfTest} from './qc-uat-isolation-foundation.mjs'
if(process.argv.length===3 && process.argv[2]==='--self-test'){
  selfTest()
}else if(process.argv.length===3 && process.argv[2]==='--emulator'){
  assertDemoEnvironment()
  selfTest()
  const {initializeTestEnvironment,assertSucceeds,assertFails}=await import('@firebase/rules-unit-testing')
  const {doc,collection,getDoc,getDocs,setDoc,deleteDoc,updateDoc,serverTimestamp}=await import('firebase/firestore')
  const [host,port]=process.env.FIRESTORE_EMULATOR_HOST.split(':')
  const env=await initializeTestEnvironment({projectId:demoProject,firestore:{host,port:Number(port),rules:candidateRules()}})
  let n=0
  const db=(uid,claims={})=>env.authenticatedContext(uid,claims).firestore()
  const marker=(enabled=true,workspace='cutover')=>({enabled,workspace,testOnly:true})
  const probe=(d,uid)=>doc(d,...probePath(uid))
  const data=uid=>({ownerUid:uid,testOnly:true,kind:'isolation-probe',createdAt:serverTimestamp()})
  const check=async(label,op,deny=false)=>{await (deny?assertFails(op):assertSucceeds(op));n++;console.log('PASS: '+label)}
  try{
    await env.clearFirestore()
    await env.withSecurityRulesDisabled(async c=>{
      const d=c.firestore()
      for(const uid of ['prodOwner','staleUat','claimOnly','collision'])await setDoc(doc(d,'users',uid),{active:true,role:'owner',status:'approved',username:uid})
      await setDoc(doc(d,'daily_plans','synthetic-prod'),{testOnly:true})
      await setDoc(doc(d,'qc_records','synthetic-prod'),{formType:'spray',inputtedBy:'prodOwner',testOnly:true})
      for(const uid of ['uatA','uatB','staleUat','collision'])await setDoc(doc(d,'qc_uat_identities',uid),marker())
      await setDoc(doc(d,'qc_uat_identities','disabledUat'),marker(false))
      await setDoc(doc(d,'qc_uat_identities','wrongWorkspace'),marker(true,'other'))
    })
    const prod=db('prodOwner'),a=db('uatA',{qcUat:true}),b=db('uatB',{qcUat:true}),stale=db('staleUat'),noClaim=db('uatB'),claimOnly=db('claimOnly',{qcUat:true}),collision=db('collision',{qcUat:true}),anon=env.unauthenticatedContext().firestore()
    await check('production Owner can still read existing root plan',getDoc(doc(prod,'daily_plans','synthetic-prod')))
    await check('production Owner can still write root plan',setDoc(doc(prod,'daily_plans','synthetic-prod2'),{testOnly:true}))
    await check('production Owner can still read QC',getDoc(doc(prod,'qc_records','synthetic-prod')))
    const reg={username:'fresh',email:'fresh@example.invalid',requestedRole:'manager',createdAt:serverTimestamp(),source:'synthetic'}
    await check('ordinary new identity retains legacy registration request',setDoc(doc(db('fresh'),'registration_requests','fresh'),reg))
    await check('UAT marker without claim cannot submit root registration',setDoc(doc(noClaim,'registration_requests','uatB'),reg),true)
    await check('UAT with claim cannot submit root registration',setDoc(doc(a,'registration_requests','uatA'),reg),true)
    await check('UAT cannot read production plan',getDoc(doc(a,'daily_plans','synthetic-prod')),true)
    await check('UAT cannot write production plan',setDoc(doc(a,'daily_plans','synthetic-prod3'),{testOnly:true}),true)
    await check('UAT cannot read production QC',getDoc(doc(a,'qc_records','synthetic-prod')),true)
    await check('stale token with active root Owner profile cannot read production',getDoc(doc(stale,'daily_plans','synthetic-prod')),true)
    await check('stale token with active root Owner profile cannot write production',setDoc(doc(stale,'daily_plans','synthetic-prod4'),{testOnly:true}),true)
    await check('claim-only identity with root Owner profile cannot read production',getDoc(doc(claimOnly,'daily_plans','synthetic-prod')),true)
    await check('claim-only identity cannot write isolated probe',setDoc(probe(claimOnly,'claimOnly'),data('claimOnly')),true)
    await check('claim without marker or root profile cannot write probe',setDoc(probe(db('unmarked',{qcUat:true}),'unmarked'),data('unmarked')),true)
    await check('identity collision with production profile cannot write probe',setDoc(probe(collision,'collision'),data('collision')),true)
    await check('marker without claim cannot write probe',setDoc(probe(noClaim,'uatB'),data('uatB')),true)
    await check('disabled UAT identity denied',setDoc(probe(db('disabledUat',{qcUat:true}),'disabledUat'),data('disabledUat')),true)
    await check('wrong workspace identity denied',setDoc(probe(db('wrongWorkspace',{qcUat:true}),'wrongWorkspace'),data('wrongWorkspace')),true)
    await check('ordinary production Owner denied probe',setDoc(probe(prod,'prodOwner'),data('prodOwner')),true)
    await check('anonymous denied probe',getDoc(probe(anon,'uatA')),true)
    await check('extra fields denied',setDoc(probe(a,'uatA'),{...data('uatA'),actualAreaHa:1}),true)
    await check('non-synthetic marker denied',setDoc(probe(a,'uatA'),{...data('uatA'),testOnly:false}),true)
    await check('wrong owner denied',setDoc(probe(a,'uatA'),data('uatB')),true)
    await check('arbitrary document ID denied',setDoc(probe(a,'other'),data('uatA')),true)
    await check('arbitrary workspace denied',setDoc(doc(a,'qc_uat_workspaces','other','probes','uatA'),data('uatA')),true)
    await check('unimplemented UAT collections remain denied',setDoc(doc(a,'qc_uat_workspaces','cutover','qc_records','x'),data('uatA')),true)
    await check('UAT cannot modify identity allowlist',setDoc(doc(a,'qc_uat_identities','uatA'),marker()),true)
    await check('production Owner cannot modify UAT allowlist',setDoc(doc(prod,'qc_uat_identities','prodOwner'),marker()),true)
    await check('allowlisted UAT can create own synthetic probe',setDoc(probe(a,'uatA'),data('uatA')))
    await check('allowlisted UAT can read own probe',getDoc(probe(a,'uatA')))
    await check('other UAT cannot read probe',getDoc(probe(b,'uatA')),true)
    await check('production Owner cannot read probe',getDoc(probe(prod,'uatA')),true)
    await check('UAT cannot list probes',getDocs(collection(a,'qc_uat_workspaces','cutover','probes')),true)
    await check('UAT cannot update probe',updateDoc(probe(a,'uatA'),{kind:'other'}),true)
    await check('UAT cannot delete probe',deleteDoc(probe(a,'uatA')),true)
    console.log('SUCCESS: '+n+' isolated UAT foundation rule checks passed (demo emulator only)')
  }finally{try{await env.clearFirestore()}finally{await env.cleanup()}}
}else throw Error('Use --self-test or --emulator')
